export const norm = (s) => String(s || '').toLowerCase().normalize('NFC').replace(/[\s.,!?~'"“”‘’()[\]{}·…\-_/]+/g, '');
// 띄어쓰기는 한 칸으로 남긴 글 (낱말 경계를 알기 위해)
const spaced = (s) => ` ${String(s || '').toLowerCase().normalize('NFC').replace(/[\s.,!?~'"“”‘’()[\]{}·…\-_/]+/g, ' ').trim()} `;
const esc = (c) => c.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
// 낱말 찾기: 글자 사이 띄어쓰기는 무시("총 쏘기" = "총쏘기")하되, 짧은 낱말(minLen 이하)은 낱말 첫머리에서만 찾음("커피가"≠"피가")
function finder(word, startUpTo) {
  const w = norm(word);
  return new RegExp(`${w.length <= startUpTo ? '\\s' : ''}${[...w].map(esc).join('\\s?')}`, 'g');
}
const found = (sp, word, startUpTo = 2) => finder(word, startUpTo).test(sp);
const cut = (sp, word, startUpTo = 2) => sp.replace(finder(word, startUpTo), ' ');

