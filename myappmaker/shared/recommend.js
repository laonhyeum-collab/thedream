export const ALL_RECS = THEMES.flatMap((t) => t.recs);

const has = (sp, words) => words.filter((w) => found(sp, w));

// 글 안의 걸러 낼 말 찾기 (기획서 검사에도 씀)
export function checkText(raw) {
  const sp = spaced(raw);
  const existing = EXISTING.filter((e) => e.names.some((n) => found(sp, n)));
  return { violence: has(sp, VIOLENCE), blocked: has(sp, BLOCKED), soft: has(sp, SOFT), existing };
}
// 관심사·놀이 방식 낱말: 한 글자 낱말("봄", "책")만 첫머리에서 찾음 ("돌봄"≠"봄")
const kwHit = (sp, k) => found(sp, k, 1);

function baseRec(baseId) {
  const b = topicById(baseId);
  return { id: `base:${b.id}`, themeId: null, themeEmoji: b.emoji, base: b.id, emoji: b.emoji, title: b.name, summary: b.summary, learn: b.learn, hero: b.hint.character, place: b.hint.place };
}

// 관심사 글 → { notices, recs, themes }
export function recommend(raw, { limit = 6 } = {}) {
  const notices = [];
  let text = spaced(raw);
  if (!text.trim()) return { notices, recs: [], themes: [] };

  const chk = checkText(raw);
  if (chk.blocked.length) {
    notices.push({ kind: 'blocked', text: '학교에서 만들 수 없는 내용이 들어 있어요. 친구들과 함께 즐길 수 있는 다른 주제를 이야기해 볼까요?' });
    return { notices, recs: [], themes: [] };
  }
  for (const e of chk.existing) {
    notices.push({ kind: 'existing', text: `「${e.label}」은(는) 이미 있는 게임·캐릭터라서 그대로 만들 수 없어요. 좋아하는 점(${e.like})을 살려 나만의 게임으로 바꿔 봤어요!` });
    for (const n of e.names) text = cut(text, n);
    text += ` ${e.q} `;
  }
  if (chk.violence.length) {
    notices.push({ kind: 'violence', text: '다치게 하거나 무서운 내용은 초등학생 게임으로 만들 수 없어요. 대신 구하고·지키고·피하는 평화로운 게임을 추천할게요.' });
    for (const w of chk.violence) text = cut(text, w);
  } else if (chk.soft.length) {
    notices.push({ kind: 'soft', text: '싸우는 대신 구하고·고치고·피하는 방식으로 바꿔서 추천할게요.' });
  }

  const themes = THEMES.map((th) => ({ th, score: th.kw.filter((k) => kwHit(text, k)).length })).filter((x) => x.score > 0).sort((a, b) => b.score - a.score).map((x) => x.th);
  const mechs = MECHS.filter((m) => m.kw.some((k) => kwHit(text, k)));
  const out = [];
  const add = (r) => { if (r && r.learn && !out.some((o) => o.id === r.id)) out.push(r); };

  for (const m of mechs) {
    for (const th of themes) {
      const same = th.recs.find((r) => r.base === m.base);
      if (same) add(same);
      else {
        const b = topicById(m.base);
        add({ id: `${th.id}:${m.base}:mix`, themeId: th.id, themeEmoji: th.emoji, base: m.base, emoji: th.emoji, title: `${th.label} ${m.word}`,
          summary: `「${b.name}」 놀이 방식에 ${th.label} 이야기를 더한 나만의 게임`, learn: th.recs[0].learn, hero: th.hero, place: th.place });
      }
    }
  }
  // 관심사별 추천을 골고루 섞기
  for (let i = 0; i < 3; i++) for (const th of themes) add(th.recs[i]);
  if (!themes.length) for (const m of mechs) { ALL_RECS.filter((r) => r.base === m.base).slice(0, 3).forEach(add); add(baseRec(m.base)); }
  if (!out.length && (chk.violence.length || chk.soft.length)) ['job', 'eco', 'sea'].forEach((id) => add(THEMES.find((t) => t.id === id).recs.find((r) => r.base === 'maze-escape' || r.base === 'jungle-survival' || r.base === 'fruit-bomb')));

  return { notices, recs: out.slice(0, limit), themes: themes.map((t) => t.label) };
}

// 아이디어가 없을 때: 분야가 겹치지 않게 골라 보여 주기
export function surprise(n = 6, rand = Math.random) {
  const pool = [...THEMES].sort(() => rand() - 0.5).slice(0, n);
  return pool.map((t) => t.recs[Math.floor(rand() * t.recs.length)]);
}

